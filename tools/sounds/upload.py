"""Uploads the built sounds (assets/sounds) to Roblox and writes their ids to
src/ReplicatedStorage/Shared/SoundIds.luau.

Uses the Open Cloud Assets API. Create a key at create.roblox.com/credentials with
the Assets API (read and write) for the account or group that owns the experience:
audio only plays in experiences its owner may use it in.

    set ROBLOX_API_KEY=...
    python tools/sounds/upload.py --group-id 1234      (or --user-id 1234)

Files already uploaded with the same contents are skipped (tools/sounds/uploaded.json),
so after rebuilding, only changed cues go up again. Audio uploads count against the
account's monthly audio quota.
"""
import argparse
import hashlib
import json
import os
import sys
import time
import urllib.error
import urllib.request
import uuid

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BUILT = os.path.join(ROOT, "assets", "sounds")
LEDGER = os.path.join(os.path.dirname(os.path.abspath(__file__)), "uploaded.json")
IDS = os.path.join(ROOT, "src", "ReplicatedStorage", "Shared", "SoundIds.luau")
API = "https://apis.roblox.com/assets/v1/"


def call(method, url, key, body=None, content_type=None):
    request = urllib.request.Request(url, data=body, method=method, headers={"x-api-key": key})
    if content_type:
        request.add_header("Content-Type", content_type)
    try:
        with urllib.request.urlopen(request) as response:
            return json.load(response)
    except urllib.error.HTTPError as error:
        sys.exit(f"{method} {url} failed: {error.code} {error.read().decode(errors='replace')}")


def upload(path, cue, creator, key):
    boundary = uuid.uuid4().hex
    meta = {
        "assetType": "Audio",
        "displayName": "Rocket " + cue.replace("/", " "),
        "description": "Rocket music (HoliznaCC0, CC0)" if cue.startswith("music/") else "Rocket sound effect (Kenney, CC0)",
        "creationContext": {"creator": creator},
    }
    with open(path, "rb") as f:
        data = f.read()
    body = (
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"request\"\r\n\r\n{json.dumps(meta)}\r\n"
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"fileContent\"; filename=\"{os.path.basename(path)}\"\r\n"
        f"Content-Type: audio/ogg\r\n\r\n"
    ).encode() + data + f"\r\n--{boundary}--\r\n".encode()
    operation = call("POST", API + "assets", key, body, f"multipart/form-data; boundary={boundary}")
    for _ in range(60):
        if operation.get("done"):
            response = operation.get("response") or {}
            if "assetId" not in response:
                sys.exit(f"{cue}: upload finished without an asset id: {operation}")
            return response["assetId"]
        time.sleep(1)
        operation = call("GET", API + operation["path"], key)
    sys.exit(f"{cue}: still processing after a minute; run again later")


def write_ids(ledger):
    lines = [
        "-- Generated by tools/sounds/upload.py: the uploaded asset id of each built sound",
        "-- (assets/sounds/<cue>.ogg). Cues missing here play only in Studio, from the copy",
        "-- tools/sounds/build.py --studio puts in Studio's content folder (see UI/Sfx).",
        "return table.freeze({",
    ]
    for cue in sorted(ledger):
        lines.append(f'    ["{cue}"] = "rbxassetid://{ledger[cue]["assetId"]}",')
    lines.append("})")
    with open(IDS, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    owner = parser.add_mutually_exclusive_group(required=True)
    owner.add_argument("--user-id")
    owner.add_argument("--group-id")
    parser.add_argument("--dry-run", action="store_true", help="list what would be uploaded")
    args = parser.parse_args()
    key = os.environ.get("ROBLOX_API_KEY")
    if not key and not args.dry_run:
        sys.exit("Set ROBLOX_API_KEY first")
    creator = {"userId": args.user_id} if args.user_id else {"groupId": args.group_id}

    ledger = json.load(open(LEDGER)) if os.path.exists(LEDGER) else {}
    for folder, _, files in sorted(os.walk(BUILT)):
        for name in sorted(files):
            if not name.endswith(".ogg"):
                continue
            path = os.path.join(folder, name)
            cue = os.path.relpath(path, BUILT)[:-4].replace(os.sep, "/")
            digest = hashlib.sha256(open(path, "rb").read()).hexdigest()
            known = ledger.get(cue)
            if known and known["sha256"] == digest and known.get("creator") == creator:
                continue
            if args.dry_run:
                print("would upload", cue)
                continue
            asset_id = upload(path, cue, creator, key)
            ledger[cue] = {"sha256": digest, "assetId": asset_id, "creator": creator}
            print(f"{cue:12s} rbxassetid://{asset_id}")
            with open(LEDGER, "w", newline="\n") as f:
                json.dump(ledger, f, indent=2, sort_keys=True)
    if not args.dry_run:
        write_ids(ledger)
        print("Wrote", os.path.relpath(IDS, ROOT))


if __name__ == "__main__":
    main()
