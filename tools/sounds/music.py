"""Builds the game's music from the MP3s in assets/sounds/Earth Music and
assets/sounds/Space Music (HoliznaCC0, CC0).

Each track is loudness-matched (two-pass EBU R128 to -20 LUFS, linear gain, so the
mix and dynamics stay as they are and no song jumps out louder than another) and
written as stereo Ogg Vorbis to assets/sounds/music/<earth|space>/<slug>.ogg. The
track list goes to src/ReplicatedStorage/Shared/MusicTracks.luau for MusicController.

    python tools/sounds/music.py            # build every track
    python tools/sounds/music.py --studio   # also copy them into Studio's content folder
                                            # (rbxasset://sounds/rocket/music/...)

Then tools/sounds/upload.py uploads them with the other sounds (their ids land in
Shared/SoundIds); until then only Studio plays them. Needs ffmpeg on PATH.
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOUNDS = os.path.join(ROOT, "assets", "sounds")
SOURCES = {"earth": os.path.join(SOUNDS, "Earth Music"), "space": os.path.join(SOUNDS, "Space Music")}
OUTPUT = os.path.join(SOUNDS, "music")
TRACKS = os.path.join(ROOT, "src", "ReplicatedStorage", "Shared", "MusicTracks.luau")
TARGET_LUFS = -20


def title_of(filename):
    """'HoliznaCC0 - Tokyo Sunset ( Lofi , Peaceful , Soft ).mp3' -> 'Tokyo Sunset'."""
    name = os.path.splitext(filename)[0]
    name = name.split(" - ", 1)[-1]
    return re.sub(r"\s*\(.*$", "", name).strip()


def slug_of(title):
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")


def measure(path):
    """First loudnorm pass: the track's measured loudness figures."""
    result = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", path, "-af",
                             f"loudnorm=I={TARGET_LUFS}:TP=-1.5:LRA=11:print_format=json", "-f", "null", "-"],
                            capture_output=True, text=True)
    text = result.stderr
    return json.loads(text[text.rindex("{"):text.rindex("}") + 1])


def encode(path, out, stats):
    os.makedirs(os.path.dirname(out), exist_ok=True)
    loudnorm = (f"loudnorm=I={TARGET_LUFS}:TP=-1.5:LRA=11:linear=true:"
                f"measured_I={stats['input_i']}:measured_TP={stats['input_tp']}:"
                f"measured_LRA={stats['input_lra']}:measured_thresh={stats['input_thresh']}:offset={stats['target_offset']}")
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", path, "-af", loudnorm,
                    "-ar", "48000", "-ac", "2", "-c:a", "libvorbis", "-q:a", "3", out], check=True)


def duration(path):
    result = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
                            capture_output=True, text=True, check=True)
    return float(result.stdout.strip())


def studio_content():
    versions = os.path.join(os.environ.get("LOCALAPPDATA", ""), "Roblox", "Versions")
    installs = [os.path.join(versions, d) for d in os.listdir(versions)] if os.path.isdir(versions) else []
    installs = [d for d in installs if os.path.isfile(os.path.join(d, "RobloxStudioBeta.exe"))]
    return os.path.join(max(installs, key=os.path.getmtime), "content", "sounds") if installs else None


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--studio", action="store_true", help="copy the built tracks into Studio's content folder")
    args = parser.parse_args()
    playlists = {}
    built = set()
    for mood, folder in SOURCES.items():
        playlists[mood] = []
        for name in sorted(os.listdir(folder)):
            if not name.lower().endswith(".mp3"):
                continue
            title = title_of(name)
            cue = f"music/{mood}/{slug_of(title)}"
            out = os.path.join(SOUNDS, cue + ".ogg")
            stats = measure(os.path.join(folder, name))
            encode(os.path.join(folder, name), out, stats)
            seconds = duration(out)
            playlists[mood].append((cue, title, seconds))
            built.add(os.path.normpath(out))
            print(f"{cue:40s} {title}: {float(stats['input_i']):.1f} -> {TARGET_LUFS} LUFS, {seconds:.0f}s")
    for folder, _, files in os.walk(OUTPUT):
        for name in files:
            path = os.path.normpath(os.path.join(folder, name))
            if name.endswith(".ogg") and path not in built:
                os.remove(path)
                print("removed", os.path.relpath(path, SOUNDS))
    lines = [
        "-- Generated by tools/sounds/music.py: the music each mood shuffles through. `cue` is",
        "-- the built file (assets/sounds/<cue>.ogg, its id in Shared/SoundIds once uploaded).",
        "return table.freeze({",
    ]
    for mood, tracks in playlists.items():
        lines.append(f"    {mood} = table.freeze({{")
        for cue, title, seconds in tracks:
            lines.append(f'        table.freeze({{ cue = "{cue}", title = "{title}", seconds = {seconds:.1f} }}),')
        lines.append("    }),")
    lines.append("})")
    with open(TRACKS, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("Wrote", os.path.relpath(TRACKS, ROOT))
    if args.studio:
        content = studio_content()
        if not content:
            sys.exit("No Roblox Studio install found under %LOCALAPPDATA%/Roblox/Versions")
        target = os.path.join(content, "rocket", "music")
        shutil.rmtree(target, ignore_errors=True)
        shutil.copytree(OUTPUT, target)
        print("Copied to", target)


if __name__ == "__main__":
    main()
